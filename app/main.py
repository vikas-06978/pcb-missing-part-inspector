@app.get("/api/project")
def get_project() -> dict[str, Any]:
    return _project_payload(storage.get_or_create_active())


@app.post("/api/project")
def create_project(payload: ProjectCreate = Body(default=ProjectCreate())) -> dict[str, Any]:
    return _project_payload(storage.create_project(payload.name))


@app.patch("/api/project")
def patch_project(payload: ProjectPatch) -> dict[str, Any]:
    project = _require_project()
    if payload.name is not None:
        project.name = payload.name.strip() or project.name
    if payload.sensitivity is not None:
        project.sensitivity = payload.sensitivity
    storage.save_project(project)
    return _project_payload(project)


@app.post("/api/project/reference")
def upload_reference(file: UploadFile = File(...)) -> dict[str, Any]:
    project = storage.get_or_create_active()
    image = to_working_size(_read_upload(file))
    storage.store_reference(project, image, original_filename=file.filename or "")
    return _project_payload(project)


@app.get("/api/project/reference.png")
def reference_image() -> FileResponse:
    project = _require_project()
    return _png(project.reference_path)


@app.put("/api/project/parts")
def save_parts(payload: PartsPayload) -> dict[str, Any]:
    project = _require_project()
    if project.reference is None:
        raise _bad_request("Upload a reference board photo first.")

    width, height = project.reference.width, project.reference.height
    parts: list[storage.Part] = []

    for index, incoming in enumerate(payload.parts, start=1):
        x, y, w, h = incoming.bbox
        x = max(0, min(x, width - 1))
        y = max(0, min(y, height - 1))
        w = max(4, min(w, width - x))
        h = max(4, min(h, height - y))

        name = incoming.name.strip() or f"Part {index}"
        parts.append(
            storage.Part(
                id=incoming.id or storage.Part.new(name, [x, y, w, h]).id,
                name=name,
                bbox=[x, y, w, h],
            )
        )

    project.parts = parts
    storage.save_project(project)
    return _project_payload(project)


@app.post("/api/project/suggest")
def suggest() -> dict[str, Any]:
    project = _require_project()
    reference = _require_reference(project)
    started = time.perf_counter()
    suggestions = suggest_parts(reference)
    return {
        "suggestions": suggestions,
        "count": len(suggestions),
        "elapsed_ms": round((time.perf_counter() - started) * 1000, 1),
    }


@app.get("/api/project/export")
def export_project() -> JSONResponse:
    project = _require_project()
    payload = storage.export_project(project)
    safe_name = "".join(c for c in project.name if c.isalnum() or c in " -_").strip()
    filename = f"{safe_name or 'board'}.pcbproj.json"
    return JSONResponse(
        payload,
        headers={
            "Content-Disposition": f'attachment; filename="{filename}"',
            **NO_STORE,
        },
    )


@app.post("/api/project/import")
def import_project(file: UploadFile = File(...)) -> dict[str, Any]:
    import json

    raw = file.file.read(MAX_UPLOAD_BYTES + 1)
    if len(raw) > MAX_UPLOAD_BYTES:
        raise _bad_request("That project file is too large.")
    try:
        payload = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise _bad_request("That file is not a readable project export.") from exc

    try:
        project = storage.import_project(payload)
    except ValueError as exc:
        raise _bad_request(str(exc)) from exc
    return _project_payload(project)


