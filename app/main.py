@app.post("/api/projects/{project_id}/activate")
def activate_project(project_id: str) -> dict[str, Any]:
    project_id = _safe_id(project_id, "project id")
    project = storage.load_project(project_id)
    if project is None:
        raise HTTPException(status_code=404, detail="Project not found.")
    storage.set_active(project_id)
    return _project_payload(project)


@app.delete("/api/projects/{project_id}")
def remove_project(project_id: str) -> dict[str, Any]:
    if not storage.delete_project(_safe_id(project_id, "project id")):
        raise HTTPException(status_code=404, detail="Project not found.")
    return {"deleted": project_id}


