@app.post("/api/inspect")
def run_inspection(
    files: list[UploadFile] = File(...),
    sensitivity: str | None = Query(default=None),
) -> dict[str, Any]:
    project = _require_project()
    reference = _require_reference(project)

    if not project.parts:
        raise _bad_request(
            "Name at least one part on the reference board before inspecting."
        )
    if len(files) > MAX_TEST_IMAGES_PER_RUN:
        raise _bad_request(
            f"Upload at most {MAX_TEST_IMAGES_PER_RUN} photos at a time."
        )

    preset = sensitivity or project.sensitivity or DEFAULT_SENSITIVITY
    if preset not in SENSITIVITY_PRESETS:
        preset = DEFAULT_SENSITIVITY

    parts = [{"id": p.id, "name": p.name, "bbox": p.bbox} for p in project.parts]
    results: list[dict[str, Any]] = []

    for upload in files:
        started = time.perf_counter()
        image = fit_to_reference(to_working_size(_read_upload(upload)), reference.shape)

        result = inspect(reference, parts, image, sensitivity=preset)
        elapsed_ms = round((time.perf_counter() - started) * 1000, 1)

        run_id = storage.new_run_id()
        aligned = result.aligned_image if result.aligned_image is not None else image

        crops = {
            verdict.part_id: crop_pair(reference, aligned, verdict)
            for verdict in result.verdicts
        }

        payload: dict[str, Any] = {
            "run_id": run_id,
            "project_id": project.id,
            "filename": upload.filename or "photo",
            "created_at": time.time(),
            "elapsed_ms": elapsed_ms,
            "sensitivity": result.sensitivity,
            "thresholds": result.thresholds,
            "summary": result.summary(),
            "alignment": result.alignment.to_dict(),
            "photometric": result.photometric,
            "scene_compensation": result.scene_compensation,
            "warnings": result.warnings,
            "verdicts": [v.to_dict() for v in result.verdicts],
            "images": {
                "test": f"/api/runs/{run_id}/image/test.png",
                "aligned": f"/api/runs/{run_id}/image/aligned.png",
                "reference": f"/api/project/reference.png?v={int(project.updated_at)}",
            },
            "size": {"width": int(reference.shape[1]), "height": int(reference.shape[0])},
        }

        storage.store_run(project, run_id, payload, image, aligned, crops)
        results.append(payload)

    if sensitivity and sensitivity != project.sensitivity:
        project.sensitivity = preset
        storage.save_project(project)

    total_missing = sum(r["summary"]["missing_count"] for r in results)
    return {
        "results": results,
        "batch": {
            "count": len(results),
            "ok_count": sum(1 for r in results if r["summary"]["status"] == "present"),
            "missing_boards": sum(1 for r in results if r["summary"]["missing_count"] > 0),
            "total_missing_parts": total_missing,
        },
    }


@app.get("/api/runs")
def list_runs() -> dict[str, Any]:
    project = _require_project()
    return {"runs": storage.list_runs(project)}


@app.get("/api/runs/{run_id}")
def get_run(run_id: str) -> dict[str, Any]:
    project = _require_project()
    payload = storage.load_run(project, _safe_id(run_id, "run id"))
    if payload is None:
        raise HTTPException(status_code=404, detail="Inspection run not found.")
    return payload


@app.delete("/api/runs")
def clear_runs() -> dict[str, Any]:
    project = _require_project()
    storage.clear_runs(project)
    return {"cleared": True}


@app.get("/api/runs/{run_id}/image/{name}")
def run_image(run_id: str, name: str) -> FileResponse:
    if name not in {"test.png", "aligned.png"}:
        raise HTTPException(status_code=404, detail="Unknown image.")
    project = _require_project()
    return _png(storage.run_directory(project, _safe_id(run_id, "run id")) / name)


@app.get("/api/runs/{run_id}/crop/{part_id}/{which}.png")
def run_crop(run_id: str, part_id: str, which: str) -> FileResponse:
    if which not in {"reference", "test"}:
        raise HTTPException(status_code=404, detail="Unknown crop.")
    project = _require_project()
    directory = storage.run_directory(project, _safe_id(run_id, "run id"))
    path = directory / "crops" / f"{_safe_id(part_id, 'part id')}-{which}.png"
    return _png(path)


