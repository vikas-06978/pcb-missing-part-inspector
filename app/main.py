"""HTTP API and static file server.

Deliberately a *local* web application rather than a desktop toolkit: the
browser gives a shop-floor-grade UI (large targets, drag and drop, zoomable
canvas, printable reports) with no build step and nothing to install beyond
pip. It binds to 127.0.0.1 and never reaches the network.

Endpoints are thin: validate, call ``app.vision``, serialise. All the
interesting behaviour lives in the vision layer, which is importable and
testable without starting a server.
"""

from __future__ import annotations

import re
import time
from pathlib import Path
from typing import Any

import numpy as np
from fastapi import Body, FastAPI, File, HTTPException, Query, UploadFile
from fastapi.responses import FileResponse, HTMLResponse, JSONResponse, Response
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field, field_validator

from app import storage
from app.config import (
    ALLOWED_UPLOAD_TYPES,
    APP_NAME,
    APP_VERSION,
    DEFAULT_SENSITIVITY,
    MAX_TEST_IMAGES_PER_RUN,
    MAX_UPLOAD_BYTES,
    SENSITIVITY_PRESETS,
    WEB_DIR,
    WORKING_LONG_EDGE,
)
from app.imaging import ImageError, decode_upload, fit_to_reference, to_working_size
from app.vision import crop_pair, inspect, suggest_parts

app = FastAPI(title=APP_NAME, version=APP_VERSION, docs_url="/api/docs", redoc_url=None)

NO_STORE = {"Cache-Control": "no-store, max-age=0"}


# --------------------------------------------------------------------------
# Request models
# --------------------------------------------------------------------------


class PartIn(BaseModel):
    id: str | None = None
    name: str = Field(default="", max_length=80)
    bbox: list[int] = Field(min_length=4, max_length=4)

    @field_validator("bbox")
    @classmethod
    def _positive_size(cls, value: list[int]) -> list[int]:
        if value[2] <= 0 or value[3] <= 0:
            raise ValueError("Box width and height must be positive.")
        return [int(v) for v in value]


class PartsPayload(BaseModel):
    parts: list[PartIn] = Field(default_factory=list, max_length=400)


class ProjectPatch(BaseModel):
    name: str | None = Field(default=None, max_length=120)
    sensitivity: str | None = None

    @field_validator("sensitivity")
    @classmethod
    def _known_preset(cls, value: str | None) -> str | None:
        if value is not None and value not in SENSITIVITY_PRESETS:
            raise ValueError("Unknown sensitivity preset.")
        return value


class ProjectCreate(BaseModel):
    name: str = Field(default="Untitled board", max_length=120)


# --------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------


def _bad_request(message: str) -> HTTPException:
    return HTTPException(status_code=400, detail=message)


def _require_project() -> storage.Project:
    project = storage.get_active()
    if project is None:
        raise HTTPException(status_code=404, detail="No active project.")
    return project


def _require_reference(project: storage.Project) -> np.ndarray:
    if project.reference is None or not project.reference_path.exists():
        raise _bad_request("Upload a reference board photo first.")
    return storage.load_reference(project)


def _read_upload(upload: UploadFile) -> np.ndarray:
    if upload.content_type and upload.content_type not in ALLOWED_UPLOAD_TYPES:
        raise _bad_request(
            f"'{upload.filename}' is a {upload.content_type} file. "
            "Upload a JPEG, PNG, BMP, WEBP or TIFF photo."
        )

    data = upload.file.read(MAX_UPLOAD_BYTES + 1)
    if len(data) > MAX_UPLOAD_BYTES:
        raise _bad_request(
            f"'{upload.filename}' is larger than {MAX_UPLOAD_BYTES // (1024 * 1024)} MB."
        )

    try:
        return decode_upload(data)
    except ImageError as exc:
        raise _bad_request(f"{upload.filename}: {exc}") from exc


def _project_payload(project: storage.Project) -> dict[str, Any]:
    payload = project.to_dict()
    payload["reference_url"] = (
        f"/api/project/reference.png?v={int(project.updated_at)}"
        if project.reference
        else None
    )
    payload["run_count"] = len(storage.list_runs(project))
    return payload


def _png(path: Path) -> FileResponse:
    if not path.exists():
        raise HTTPException(status_code=404, detail="Image not found.")
    return FileResponse(path, media_type="image/png", headers=NO_STORE)


#: Identifiers are generated by this application, never typed by a user, so an
#: allow-list is both sufficient and the cheapest way to close path traversal.
SAFE_ID = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


def _safe_id(value: str, kind: str) -> str:
    if not SAFE_ID.fullmatch(value):
        raise HTTPException(status_code=400, detail=f"Invalid {kind}.")
    return value


